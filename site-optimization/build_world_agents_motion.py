"""Adapt the supplied Vancouver+ Webflow IX2 timelines to the product DOM.
The runtime and action values are sourced from dist/模板/1, not reimplemented.
Only selectors/event targets and page lifecycle are adapted for the React route.
"""
from pathlib import Path
import json,copy,shutil
root=Path(__file__).resolve().parent
source=root.parent/'dist'/'模板'/'1'
out=root/'world-agents-motion';out.mkdir(exist_ok=True)
script=(source/'js'/'app.ca15e308d.js').read_text(encoding='utf-8')
init=script.index("Webflow.require('ix2').init(")
config,_=json.JSONDecoder().raw_decode(script[script.index('{"events":',init):])
# Keep the actual runtime, omit unrelated page interactions and commerce startup.
(out/'webflow-runtime.js').write_text(script[:init],encoding='utf-8')
shutil.copy2(source/'js'/'jquery-3.5.1.min.dc5e7f18c8.js',out/'jquery.js')
selector_map={'.navbar':'.wa-page .wa-header','.animate-on-load-1st':'.wa-page .wa-hero h1','.animate-on-load-2st':'.wa-page .wa-hero-description','.animate-on-load-3rd':'.wa-page .wa-hero .wa-actions','.animate-on-load-4rd':'.wa-page .wa-product-stage','.app-container':'.wa-hero-window','.app-info-01':'.wa-float-model','.app-info-02':'.wa-float-flow','.light-wrapper':'.wa-pointer-light','.button-gradient':'.wa-button-gradient','.white-background-button-color':'.wa-button-fill','.link-block-underline':'.wa-nav-underline'}
keys=['a-16','a-12','a-60','a-21','a-24','a-54','a-67','a-68','a','a-2']
actions={k:copy.deepcopy(config['actionLists'][k]) for k in keys}
for key,action in actions.items():
 groups=action.get('actionItemGroups',[])+[group for param in action.get('continuousParameterGroups',[]) for group in param['continuousActionGroups']]
 for group in groups:
  kept=[]
  for item in group['actionItems']:
   target=item['config'].get('target',{})
   if target.get('selector') in selector_map:
    target['selector']=selector_map[target['selector']];target.pop('selectorGuids',None)
   elif target.get('useEventTarget') is True:
    target.pop('id',None)
   elif not target and key in ['a-67','a-68']:
    item['config']['target']={'useEventTarget':True}
   else:continue
   kept.append(item)
  group['actionItems']=kept
# The hero now presents the screenshot alone; drop the removed info-card tracks.
for parameter in actions['a-21']['continuousParameterGroups']:
 for frame in parameter['continuousActionGroups']:
  frame['actionItems'] = [item for item in frame['actionItems'] if item['config']['target'].get('selector') not in ['.wa-float-model', '.wa-float-flow']]
# Use source event definitions, including continuous interpolation and smoothing.
events={}
def event(source_id,new_id,selector=None,page=False,action=None,desktop=False):
 e=copy.deepcopy(config['events'][source_id]);e['id']=new_id
 target={'id':'world-of-agents','appliesTo':'PAGE','styleBlockIds':[]} if page else {'selector':selector,'appliesTo':'CLASS'}
 e['target']=target;e['targets']=[target]
 e['action']['config'].pop('autoStopEventId',None)
 if action:e['action']['config']['actionListId']=action
 if desktop:e['mediaQueries']=['main']
 events[new_id]=e
 return e
event('e-62','wa-load',page=True)
event('e-64','wa-hero-scroll','.wa-page .wa-hero',desktop=True)
event('e-390','wa-header-scroll',page=True)
event('e-434','wa-reveal','.wa-page .wa-heading, .wa-page .wa-feature-copy, .wa-page .wa-feature-picture, .wa-page .wa-architecture, .wa-page .wa-closing')
event('e-415','wa-cards','.wa-page .wa-principles article, .wa-page .wa-bento>article, .wa-page .wa-interfaces article, .wa-page .wa-evidence article')
event('e-301','wa-card-light','.wa-page .wa-bento>article, .wa-page .wa-evidence article',desktop=True)
a=event('e-470','wa-button-in','.wa-page .wa-button-outline',desktop=True);a['action']['config']['autoStopEventId']='wa-button-out'
a=event('e-471','wa-button-out','.wa-page .wa-button-outline',desktop=True);a['action']['config']['autoStopEventId']='wa-button-in'
a=event('e-468','wa-link-in','.wa-page .wa-nav nav button',desktop=True);a['action']['config']['autoStopEventId']='wa-link-out'
a=event('e-469','wa-link-out','.wa-page .wa-nav nav button',desktop=True);a['action']['config']['autoStopEventId']='wa-link-in'
(out/'config.json').write_text(json.dumps({'events':events,'actionLists':actions,'site':config['site']},ensure_ascii=False),encoding='utf-8')
(out/'README.md').write_text('Vancouver+ template Webflow IX2 runtime and adapted interaction data.\nGenerated by build_world_agents_motion.py from the user supplied template.\nAction timings, easing, load stagger, scroll perspective, hover and pointer smoothing are preserved.\nCommerce initialization and unrelated page event configurations are omitted.\n',encoding='utf-8')
print('Prepared Vancouver+ IX2:',len(events),'events,',len(actions),'source timelines')
